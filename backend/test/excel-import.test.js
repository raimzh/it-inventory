'use strict';
/**
 * Разбор строки при импорте из Excel: даты, колонки, серийные номера.
 *
 *   npm run test:import
 *
 * Все три проверяемых здесь дефекта портили данные молча, без единой
 * ошибки в журнале импорта:
 *
 *   • заголовки выгрузки и импорта назывались по-разному, и файл,
 *     выгруженный из системы и залитый обратно, терял остаточную
 *     стоимость, местоположение, владельца и комментарий;
 *
 *   • `new Date('04.01.2026')` возвращает 31 марта — дата не терялась,
 *     а подменялась правдоподобной, но неверной;
 *
 *   • в колонку серийного номера попадало наименование, и так в учёт
 *     легли 380 записей, где серийником значилось название модели.
 *
 * Поэтому здесь закреплены оба формата дат, оба набора заголовков и
 * отбрасывание серийника, дословно повторяющего наименование.
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');

// Берём собранный dist, а не .ts: в CI Node 20, а снимать типы с исходника
// умеет только Node 22+. Тот же приём в scan.parse.test.js
const { parseDateCell } = require('../dist/common/excel/parse-date-cell');
const { ExcelImportService } = require('../dist/modules/assets/excel-import.service');

/**
 * Разбор одной строки. Метод не обращается к this, поэтому вызывается
 * напрямую с прототипа — поднимать ради него весь модуль с зависимостями
 * незачем.
 */
const mapRow = raw => ExcelImportService.prototype.mapRow.call(null, raw);

test('дата: ДД.ММ.ГГГГ разбирается как день-месяц-год', () => {
  assert.equal(parseDateCell('20.06.2023'), '2023-06-20');
  assert.equal(parseDateCell('30.12.2021'), '2021-12-30');
  // Тот самый случай, который new Date толковал как 31 марта
  assert.equal(parseDateCell('04.01.2026'), '2026-01-04');
});

test('дата: разделителем может быть точка, слэш или дефис', () => {
  assert.equal(parseDateCell('20/06/2023'), '2023-06-20');
  assert.equal(parseDateCell('20-06-2023'), '2023-06-20');
});

test('дата: однозначный ГГГГ-ММ-ДД остаётся как есть', () => {
  assert.equal(parseDateCell('2023-06-20'), '2023-06-20');
});

test('дата: ячейка Date берётся по UTC, без сдвига на сутки', () => {
  assert.equal(parseDateCell(new Date('2023-06-20T00:00:00Z')), '2023-06-20');
});

test('дата: несуществующая дата отвергается, а не донормируется', () => {
  // Date сам превратил бы это в 3 марта, и в учёт попала бы чужая дата
  assert.equal(parseDateCell('31.02.2023'), null);
  assert.equal(parseDateCell('20.13.2023'), null);
});

test('дата: пустая ячейка и мусор дают null', () => {
  assert.equal(parseDateCell(''), null);
  assert.equal(parseDateCell(null), null);
  assert.equal(parseDateCell(undefined), null);
  assert.equal(parseDateCell('не дата'), null);
});

test('колонки: заголовки выгрузки распознаются наравне со своими', () => {
  // Читаем таблицу сопоставления из самого модуля, чтобы тест ловил
  // расхождение, а не повторял его
  const src = require('fs').readFileSync(
    require('path').join(__dirname, '../src/modules/assets/excel-import.service.ts'), 'utf8',
  );
  const map = src.slice(src.indexOf('const COLUMN_MAP'), src.indexOf('const REQUIRED_COLS'));

  // Именно эти четыре колонки выгрузка называет иначе, чем ждал импорт
  const pairs = [
    ['Остаточная стоимость', 'residualValue'],
    ['Местоположение', 'location'],
    ['Владелец', 'ownerName'],
    ['Комментарий', 'comment'],
  ];
  for (const [header, field] of pairs) {
    assert.ok(
      map.includes(`'${header}'`),
      `заголовок выгрузки «${header}» не сопоставлен — колонка будет молча пропущена`,
    );
    assert.ok(map.includes(field), `поле ${field} отсутствует в сопоставлении`);
  }
});

test('серийный номер, повторяющий наименование, отбрасывается', () => {
  // Так в учёт попали 380 записей, где серийником значилось название
  // модели: колонки в выгрузке были перепутаны. Поиск по серийнику
  // выдавал случайную позицию из десятка одинаковых, а в указателе
  // сканирования такие значения перекрывали друг друга
  const dto = mapRow({
    'Инв. номер': '00-000898',
    'Наименование': 'Монитор, 27B2H, d: 27 дюйм, AOC',
    'Серийный номер': 'Монитор, 27B2H, d: 27 дюйм, AOC',
  });
  assert.equal(dto.name, 'Монитор, 27B2H, d: 27 дюйм, AOC');
  assert.equal(dto.serialNumber, undefined, 'копия наименования серийным номером быть не может');
});

test('настоящий серийный номер проходит', () => {
  const dto = mapRow({
    'Инв. номер': '00-000898',
    'Наименование': 'Монитор, 27B2H, d: 27 дюйм, AOC',
    'Серийный номер': 'CN12345678',
  });
  assert.equal(dto.serialNumber, 'CN12345678');
});

test('серийный номер без наименования не теряется', () => {
  // Сравнивать не с чем — отбрасывать нечего
  const dto = mapRow({ 'Инв. номер': '00-000898', 'Серийный номер': 'CN12345678' });
  assert.equal(dto.serialNumber, 'CN12345678');
});

test('совпадение проверяется после обрезки пробелов', () => {
  // parseSheet отдаёт значения как есть, лишние пробелы по краям — обычное
  // дело для выгрузок, и из-за них проверка не должна промахиваться
  const dto = mapRow({
    'Инв. номер': '00-000898',
    'Наименование': 'Ноутбук ProBook 450',
    'Серийный номер': '  Ноутбук ProBook 450  ',
  });
  assert.equal(dto.serialNumber, undefined);
});
