'use strict';
/**
 * Отказ выполнять тесты, которые пишут в базу, против боевой.
 *
 * В CI тесты работают с отдельной базой `it_inventory_test` и вреда не
 * приносят. Вредит запуск руками на рабочей машине: там в окружении
 * лежит боевая конфигурация, и прогон оставляет в учёте фикстуры —
 * тестовые ОС, позиции склада, сотрудников, движения. Так за месяц
 * накопились 48 ОС вида `E2E-*`, три позиции склада и учётка,
 * которую держал журнал аудита.
 *
 * Проверяется два признака независимо: имя базы и адрес приложения.
 * Хватает одного несовпадения, потому что промахнуться можно по-разному:
 * запустить тесты с боевым .env либо направить их на боевой порт.
 *
 * Осознанный обход — `ALLOW_PROD_DB=1`. Он оставлен намеренно: бывает
 * нужно проверить поведение именно на боевых данных, и тогда это
 * делается явным решением, а не по забывчивости.
 */

/** Порт боевого приложения (ecosystem.config.js) */
const PROD_PORT = '3001';

/**
 * Читаем .env так же, как это делает приложение. Без этого DB_NAME на
 * рабочей машине не виден, и самый частый промах — поднять приложение на
 * тестовом порту, но с боевой конфигурацией — проходил бы незамеченным.
 * В CI переменные уже заданы, а dotenv существующие не перезаписывает.
 */
try {
  require('dotenv').config();
} catch {
  // Без dotenv остаётся проверка по адресу — она не зависит от файла
}

function assertNotProductionDb() {
  if (process.env.ALLOW_PROD_DB === '1') return;

  const dbName = process.env.DB_NAME || '';
  const baseUrl = process.env.BASE_URL || '';
  const reasons = [];

  // Тестовая база обязана называться так, чтобы это было видно
  if (dbName && !/(^|_)test($|_)/.test(dbName)) {
    reasons.push(`база «${dbName}» не похожа на тестовую (ожидается имя с _test)`);
  }
  if (baseUrl.includes(`:${PROD_PORT}`)) {
    reasons.push(`адрес ${baseUrl} — это боевое приложение (порт ${PROD_PORT})`);
  }

  if (!reasons.length) return;

  throw new Error(
    'Тест пишет в базу и остановлен, чтобы не засорить учёт:\n' +
    reasons.map(r => `  • ${r}`).join('\n') +
    '\n\nЗапускайте против тестовой базы (как в CI: DB_NAME=it_inventory_test),' +
    '\nлибо, если это осознанно, задайте ALLOW_PROD_DB=1.',
  );
}

module.exports = { assertNotProductionDb };
