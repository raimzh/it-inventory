/**
 * Линейный штрихкод Code 128 (набор B) → SVG.
 *
 * Нужен для инвентаризационных наклеек: на уже наклеенных на технику
 * этикетках стоит именно линейный код с инвентарным номером, а не QR,
 * и новые наклейки обязаны читаться теми же сканерами.
 *
 * Своя реализация, а не библиотека: на машине с продом любой npm install
 * задевает node_modules, который держит запущенный PM2 (уже приводило к
 * порче зависимостей). Кодировка Code 128 детерминирована и целиком
 * покрыта тестом, поэтому цена своей реализации здесь ниже цены установки.
 *
 * Набор B (а не C) выбран потому, что инвентарные номера содержат дефис:
 * плотный числовой набор C кодирует только пары цифр.
 */

/**
 * Ширины элементов (штрих/пробел, чередуя, начиная со штриха) для каждого
 * из 107 знаков Code 128. Каждый знак — ровно 11 модулей, кроме стоп-знака
 * (13). Это свойство проверяется тестом: оно ловит опечатки в таблице.
 */
const PATTERNS = [
  '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312',
  '132212', '221213', '221312', '231212', '112232', '122132', '122231', '113222',
  '123122', '123221', '223211', '221132', '221231', '213212', '223112', '312131',
  '311222', '321122', '321221', '312212', '322112', '322211', '212123', '212321',
  '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
  '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121',
  '313121', '211331', '231131', '213113', '213311', '213131', '311123', '311321',
  '331121', '312113', '312311', '332111', '314111', '221411', '431111', '111224',
  '111422', '121124', '121421', '141122', '141221', '112214', '112412', '122114',
  '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
  '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112',
  '421211', '212141', '214121', '412121', '111143', '111341', '131141', '114113',
  '114311', '411113', '411311', '113141', '114131', '311141', '411131', '211412',
  '211214', '211232', '2331112',
];

const START_B = 104;
const STOP = 106;
/** Свободное поле по краям: без него сканер не находит границу кода. */
const QUIET_MODULES = 10;

export { PATTERNS, START_B, STOP };

/**
 * Значения знаков для строки: старт, данные, контрольная сумма, стоп.
 * Вынесено отдельно от отрисовки, чтобы кодирование можно было проверить
 * тестом без разбора SVG.
 */
export function encodeCode128B(value: string): number[] {
  const codes: number[] = [START_B];

  for (const ch of value) {
    const code = ch.charCodeAt(0) - 32;
    if (code < 0 || code > 94) {
      throw new Error(`Code 128B не кодирует символ «${ch}» (нужен ASCII 32–126)`);
    }
    codes.push(code);
  }

  // Контрольная сумма: старт плюс данные с весом позиции, по модулю 103
  let sum = START_B;
  for (let i = 1; i < codes.length; i++) sum += codes[i] * i;
  codes.push(sum % 103);

  codes.push(STOP);
  return codes;
}

interface BarcodeOptions {
  /** Ширина одного модуля в пользовательских единицах SVG */
  moduleWidth?: number;
  height?: number;
}

/**
 * SVG со штрихкодом. Именно вектор, а не canvas: термопринтер печатает
 * с высоким разрешением, и растр в 96 dpi дал бы рваные края штрихов,
 * из-за которых код читается хуже.
 */
export function code128Svg(value: string, opts: BarcodeOptions = {}): string {
  const { moduleWidth = 2, height = 100 } = opts;
  const codes = encodeCode128B(value);

  const rects: string[] = [];
  let x = QUIET_MODULES;

  for (const code of codes) {
    const pattern = PATTERNS[code];
    // Элементы чередуются штрих/пробел, начиная со штриха
    for (let i = 0; i < pattern.length; i++) {
      const width = Number(pattern[i]);
      if (i % 2 === 0) rects.push(`<rect x="${x}" y="0" width="${width}" height="${height}"/>`);
      x += width;
    }
  }

  const totalModules = x + QUIET_MODULES;
  const width = totalModules * moduleWidth;

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalModules} ${height}" ` +
    `width="${width}" height="${height}" preserveAspectRatio="none" shape-rendering="crispEdges">` +
    `<rect x="0" y="0" width="${totalModules}" height="${height}" fill="#fff"/>` +
    `<g fill="#000">${rects.join('')}</g>` +
    `</svg>`
  );
}

/** SVG в виде data-URL — чтобы вставлять как обычную картинку. */
export function code128DataUrl(value: string, opts: BarcodeOptions = {}): string {
  return `data:image/svg+xml;utf8,${encodeURIComponent(code128Svg(value, opts))}`;
}
